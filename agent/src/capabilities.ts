export const CAPABILITY_BY_ID = new Map(CAPABILITIES.map((c) => [c.id, c]));

/** Whether a capability is switched on *and* has everything it needs to run. */
export function capabilityReady(capability: Capability, config: Config): boolean {
  // A capability with no switch is on regardless of what an older config row says.
  if (!capability.alwaysOn && !config[capability.flag]) return false;
  return capability.fields.every((f) => !f.required || String(config[f.key] ?? "").trim() !== "");
}

/** The ready capabilities to name to the model. Channels are excluded: they are not abilities. */
export function capabilityLabels(config: Config): string[] {
  return CAPABILITIES.filter((c) => !c.channel && !c.preview && capabilityReady(c, config)).map(
    (c) => c.label
  );
}

/** The standing instructions of the ready capabilities, in catalogue order. */
export function capabilityInstructions(config: Config): string[] {
  return CAPABILITIES.filter((c) => c.instructions && !c.preview && capabilityReady(c, config)).map(
    (c) => c.instructions!
  );
}

/** Where the agent can be reached, which is a different claim from what it can do. */
export function channelLabels(config: Config): string[] {
  return CAPABILITIES.filter((c) => c.channel && !c.preview && capabilityReady(c, config)).map(
    (c) => c.label
  );
}

export function enabled(config: Config, id: CapabilityId): boolean {
  const capability = CAPABILITY_BY_ID.get(id);
  return capability ? capabilityReady(capability, config) : false;
}

