/**
 * Something the agent can do beyond writing. Tool capabilities give the model functions;
 * input capabilities change what a turn may carry (files, images, audio). Sent to the UI as-is.
 */
export type CapabilityId =
  | "web_search"
  | "url_fetch"
  | "file_ingest"
  | "vision"
  | "image_generation"
  | "audio_input"
  | "voice_output"
  | "scheduled_tasks"
  | "memory"
