/** The configured network the model named, or the list of them to choose from. */
async function networkNamed(ctx: ToolContext, named: string): Promise<ChainNetwork> {
  const networks = await ctx.registry.chainNetworks();
  const network = findNetwork(networks, named);
  if (!network)
    throw new Error(`no network named ${named}. Configured:\n${describeNetworks(networks)}`);
  return network;
}

/** The agent's wallet secret, drawn the first time a wallet tool needs it. */
async function walletKey(ctx: ToolContext): Promise<Hex> {
  const key = await ctx.registry.chainWalletKey(true);
  if (!key) throw new Error("the wallet could not be created");
  return key;
}

const TOOL_BY_NAME = new Map(TOOLS.map((t) => [t.name, t]));

/** The tools to offer this turn: those belonging to a ready capability. */
export function toolsFor(config: Config): ToolSpec[] {
  // A tool two ready capabilities share (search_files) is offered once.
  const names = new Set(
    CAPABILITIES.filter((c) => capabilityReady(c, config)).flatMap((c) => c.tools)
  );
  return [...names].map((name) => TOOL_BY_NAME.get(name)).filter((t): t is ToolSpec => !!t);
}

/* ------------------------------------------------------------ mcp tools -- */

/**
 * A client for one server with credentials applied; an expiring OAuth token is
 * refreshed and written back so old connections keep working.
 */
export async function mcpClientFor(
  server: McpServerRow,
  registry: DurableObjectStub<SessionRegistry>
): Promise<McpClient> {
  const headers = server.auth === "headers" ? parseHeaders(server.headers) : {};
  if (server.auth !== "oauth") return new McpClient(server.url, headers);
  // The registry owns refreshing: it holds the row, and it is the only place that can
  // keep two of this server's tools from refreshing against each other.
  const fresh = await registry.refreshMcpToken(server.id);
  return new McpClient(server.url, headers, fresh?.oauth_access_token ?? "");
}

/**
 * Run against a server, retrying once with a fresh token on a 401: the stored expiry is
 * only a guess, and the provider's refusal is the authority.
 */
export async function withMcpAuth<T>(
  server: McpServerRow,
  registry: DurableObjectStub<SessionRegistry>,
  run: (client: McpClient) => Promise<T>
): Promise<T> {
  try {
    return await run(await mcpClientFor(server, registry));
  } catch (err) {
    if (!(err instanceof McpUnauthorized) || server.auth !== "oauth") throw err;
    const refreshed = await registry.refreshMcpToken(server.id, true);
    // A refresh that cleared the tokens already explained why in actionable words; prefer that.
    if (!refreshed?.oauth_access_token) {
      throw refreshed?.last_error ? new Error(refreshed.last_error) : err;
    }
    const retried = await run(new McpClient(refreshed.url, {}, refreshed.oauth_access_token));
    // The call works again, so whatever the card was reporting is out of date.
    if (server.last_error) await registry.noteMcpError(server.id, "");
    return retried;
  }
}

/** Whether a server is switched on and has whatever it needs to authenticate. */
export function mcpServerReady(server: McpServerRow): boolean {
  if (!server.enabled || !server.url.trim()) return false;
  if (server.auth === "oauth") return server.oauth_access_token !== "";
  return true;
}

/**
 * The servers a chat may use. In a Telegram group anyone there can ask for a tool, so a
 * server switched off for groups is left out.
 */
export function mcpServersForChat(
  servers: McpServerRow[],
  chat: { source: string; chat_type: string } | undefined
): McpServerRow[] {
  const group =
    chat?.source === "telegram" && (chat.chat_type === "group" || chat.chat_type === "supergroup");
  return group ? servers.filter((s) => s.in_groups) : servers;
}

/** How the model names an attachment in `upload_id`; swapped for the server's id on call. */
export const ATTACHMENT_REF = "attachment:";

/** Whether a tool asks for an `upload_id`. */
function takesUpload(tool: { inputSchema?: { properties?: unknown } }): boolean {
  const properties = tool.inputSchema?.properties;
  return typeof properties === "object" && properties !== null && "upload_id" in properties;
}

/**
 * Whether a server takes uploads at `<base>/uploads`, inferred from a callable tool that
 * asks for an `upload_id`.
 */
export function acceptsUploads(server: McpServerRow): boolean {
  if (!mcpServerReady(server)) return false;
  const off = new Set(parseNames(server.disabled_tools));
  return parseTools(server.tools_json).some((tool) => !off.has(tool.name) && takesUpload(tool));
}

/**
 * The exact `upload_id` for each of the chat's files, added to a failure of a call that
 * took no file. A weaker model told only "pass upload_id" repeats the call without one;
 * handed the value, it copies it.
 */
function uploadHint(files: { id: string; name: string }[]): string {
  if (files.length === 0) return "";
  const each = files
    .map((f) => `upload_id="${ATTACHMENT_REF}${f.id}" for ${f.name.replace(/[\r\n]/g, " ")}`)
    .join("; ");
  return `No file was passed. To give this tool a file from this chat, pass ${each}.`;
}

/**
 * Every connected MCP server's tools as specs, schemas passed through, from the cached
 * `tools/list` so a turn adds no round trip.
 */
export function mcpToolSpecs(servers: McpServerRow[]): ToolSpec[] {
  const specs: ToolSpec[] = [];
  for (const server of servers) {
    if (!mcpServerReady(server)) continue;
    const off = new Set(parseNames(server.disabled_tools));
    for (const tool of parseTools(server.tools_json)) {
      // A tool switched off is never handed to the model, so it cannot be called.
      if (off.has(tool.name)) continue;
      specs.push({
        name: qualifiedName(server, tool.name),
        description: `[${server.name}] ${tool.description ?? tool.name}`,
        parameters: tool.inputSchema ?? { type: "object", properties: {} },
        async run(args, ctx) {
          /**
           * A call that needed a file and was sent none, made again with the one file the
           * user's latest message carried. Some models will not copy an upload_id even when
           * handed it; the file they mean is not in doubt. Undefined when it is (several
           * files, or none), or when the second call fails too.
           */
          const withLatestFile = async (sent: Record<string, unknown>) => {
            const latest = ctx.latestFiles();
            if (latest.length !== 1) return undefined;
            try {
              const id = await ctx.uploadAttachment(server, latest[0].id);
              return await withMcpAuth(server, ctx.registry, (client) =>
                client.callTool(tool.name, { ...sent, upload_id: id })
              );
            } catch {
              return undefined;
            }
          };
          try {
            // A file goes to a server only when the model hands it to one of its tools.
            const ref = typeof args.upload_id === "string" ? args.upload_id : "";
            if (ref.startsWith(ATTACHMENT_REF)) {
              const id = await ctx.uploadAttachment(server, ref.slice(ATTACHMENT_REF.length));
              args = { ...args, upload_id: id };
            }
            const call = (sent: Record<string, unknown>) =>
              withMcpAuth(server, ctx.registry, (client) => client.callTool(tool.name, sent));
            let result;
            try {
              result = await call(args);
            } catch (err) {
              const retried =
                !args.upload_id && takesUpload(tool) ? await withLatestFile(args) : undefined;
              if (!retried) throw err;
              result = retried;
            }
            return await deliverMcpOutput(result, ctx);
          } catch (err) {
            const message = err instanceof Error ? err.message : String(err);
            // Without this the card would keep advertising a server whose every call
            // is failing, because only a tool sync ever wrote that field.
            await ctx.registry.noteMcpError(server.id, message);
            const hint = !args.upload_id && takesUpload(tool) ? uploadHint(ctx.sharedFiles()) : "";
            if (hint) throw new Error(`${message}\n${hint}`);
            throw err;
          }
        },
      });
    }
  }
  return specs;
}

/** Images one tool result may put in front of the user; the rest are left out. */
const MAX_MCP_IMAGES = 10;

/**
 * Keep what a tool made for the user (images, files) as this session's attachments, and
 * tell the model how to show them. The bytes never reach the model: only links do.
 */
export async function deliverMcpOutput(result: McpToolResult, ctx: ToolContext): Promise<string> {
  const lines: string[] = [];
  const limits = ctx.settings.max_upload_bytes;
  for (const [i, image] of result.images.slice(0, MAX_MCP_IMAGES).entries()) {
    const label = `Image ${i + 1}`;
    if (base64Size(image.data) > limits.image) {
      lines.push(`(${label} was too large to show.)`);
      continue;
    }
    try {
      lines.push(
        `![${label}](${await ctx.saveImage(`data:${image.mime};base64,${image.data}`, label)})`
      );
    } catch (err) {
      lines.push(
        `(${label} could not be kept: ${err instanceof Error ? err.message : String(err)})`
      );
    }
  }
  if (result.images.length > MAX_MCP_IMAGES) {
    lines.push(`(${result.images.length - MAX_MCP_IMAGES} more images were left out.)`);
  }
  for (const file of result.files) {
    try {
      const bytes = base64ToBytes(file.data);
      lines.push(
        `[${file.name.replace(/[[\]]/g, "")}](${await ctx.saveFile(bytes, file.name, file.mime)})`
      );
    } catch (err) {
      lines.push(
        `(${file.name} could not be kept: ${err instanceof Error ? err.message : String(err)})`
      );
    }
  }
  if (lines.length === 0) return result.text;
  return [
    result.text,
    "For the user (they see these only if your reply includes them; copy each line exactly):",
    ...lines,
  ]
    .filter(Boolean)
    .join("\n\n");
}

/** Decoded size of base64 text, without decoding it. */
function base64Size(encoded: string): number {
  const padding = encoded.endsWith("==") ? 2 : encoded.endsWith("=") ? 1 : 0;
  return Math.floor((encoded.length * 3) / 4) - padding;
}

/** OpenRouter's `tools` array for those tools. */
export function toolDefinitions(config: Config) {
  return toolsFor(config).map((t) => ({
    type: "function" as const,
    function: { name: t.name, description: t.description, parameters: t.parameters },
  }));
}

/** Run one tool. Failures are returned, not thrown, so the model can correct itself. */
export async function runTool(
  name: string,
  args: Record<string, unknown>,
  ctx: ToolContext,
  /** The spec to run, for tools that live outside `TOOLS` — MCP's, for instance. */
  spec?: ToolSpec
): Promise<{ content: string; ok: boolean }> {
  const tool = spec ?? TOOL_BY_NAME.get(name);
  if (!tool) return { content: `Error: no tool named ${name}.`, ok: false };
  try {
    return { content: await tool.run(args, ctx), ok: true };
  } catch (err) {
    return {
      content: `Tool ${name} failed: ${err instanceof Error ? err.message : String(err)}`,
      ok: false,
    };
  }
}
