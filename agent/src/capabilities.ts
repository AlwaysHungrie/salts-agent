/**
 * Collect a streamed spoken answer: base64 16-bit little-endian PCM chunks, complete only
 * at stream end. A mid-stream error is thrown so the model can explain the missing note.
 */
async function spokenSamples(res: Response): Promise<Int16Array> {
  const body = res.body;
  if (!body) throw new Error("the voice model sent no stream");
  const reader = body.getReader();
  const decoder = new TextDecoder();
  const chunks: Uint8Array[] = [];
  let buffered = "";
  let bytes = 0;
  for (;;) {
    const { done, value } = await reader.read();
    buffered += done ? "" : decoder.decode(value, { stream: true });
    // Only whole lines can be parsed; whatever follows the last newline is the start
    // of one and waits for the rest of it.
    const lines = buffered.split("\n");
    buffered = done ? "" : (lines.pop() ?? "");
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed.startsWith("data:")) continue;
      const payload = trimmed.slice(5).trim();
      if (payload === "" || payload === "[DONE]") continue;
      let event: {
        error?: { message?: string };
        choices?: { delta?: { audio?: { data?: string } } }[];
      };
      try {
        event = JSON.parse(payload);
      } catch {
        // OpenRouter sends keep-alive comments and the odd non-JSON line; neither is
        // audio and neither is a failure.
        continue;
      }
      if (event.error) throw new Error(event.error.message ?? "the voice model failed mid-stream");
      const data = event.choices?.[0]?.delta?.audio?.data;
      if (!data) continue;
      const decoded = base64Bytes(data);
      bytes += decoded.length;
      chunks.push(decoded);
    }
    if (done) break;
  }
  const pcm = new Uint8Array(bytes);
  let at = 0;
  for (const chunk of chunks) {
    pcm.set(chunk, at);
    at += chunk.length;
  }
  // An odd trailing byte is half a sample and belongs to nothing; `Int16Array` cannot
  // hold it either.
  return new Int16Array(pcm.buffer, 0, Math.floor(bytes / 2));
}

function base64Bytes(base64: string): Uint8Array {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

/** Rough HTML-to-text: enough for a model to read a page, cheap enough for a Worker. */
function htmlToText(html: string): string {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();
}

type SearchResult = { title: string; url: string; description?: string };

/** A self-hosted SearXNG instance. The fallback for agents with no Brave API key. Needs `formats: [json]` in its settings.yml. */
async function searxngSearch(
  base: string,
  token: string,
  query: string,
  count: number
): Promise<SearchResult[]> {
  if (!base) throw new Error("no Brave API key and no SearXNG URL is set");
  const url = `${base}/search?q=${encodeURIComponent(query)}&format=json`;
  const headers: Record<string, string> = { Accept: "application/json" };
  if (token) headers.Authorization = `Bearer ${token}`;
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`SearXNG returned ${res.status} ${await res.text()}`);
  const json = (await res.json()) as {
    results?: { title?: string; url?: string; content?: string }[];
  };
  return (json.results ?? [])
    .filter((r) => r.url)
    .slice(0, count)
    .map((r) => ({ title: r.title ?? r.url!, url: r.url!, description: r.content }));
}

/** Brave's hosted API. The default when a key is set. */
async function braveSearch(key: string, query: string, count: number): Promise<SearchResult[]> {
  const url = `https://api.search.brave.com/res/v1/web/search?q=${encodeURIComponent(query)}&count=${count}`;
  const res = await fetch(url, {
    headers: { Accept: "application/json", "X-Subscription-Token": key },
  });
  if (!res.ok) throw new Error(`Brave returned ${res.status} ${await res.text()}`);
  const json = (await res.json()) as { web?: { results?: SearchResult[] } };
  return json.web?.results ?? [];
}

/** The 11-character video id in any YouTube link (watch, youtu.be, shorts, live, embed), or a bare id. */
export function youtubeVideoId(raw: string): string | null {
  const text = raw.trim();
  const valid = (id: string | null | undefined) => (id && /^[\w-]{11}$/.test(id) ? id : null);
  if (valid(text)) return text;
  let url: URL;
  try {
    url = new URL(text);
  } catch {
    return null;
  }
  const host = url.hostname.replace(/^(www|m|music)\./, "");
  if (host === "youtu.be") return valid(url.pathname.split("/")[1]);
  if (host !== "youtube.com" && host !== "youtube-nocookie.com") return null;
  return valid(
    url.searchParams.get("v") ?? url.pathname.match(/^\/(?:shorts|live|embed|v)\/([\w-]{11})/)?.[1]
  );
}

type YoutubeDetails = { title: string; channel: string; seconds: number };

type YoutubePlayer = {
  playabilityStatus?: { status?: string; reason?: string };
  videoDetails?: { title?: string; author?: string; lengthSeconds?: string };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: { baseUrl: string; languageCode: string; kind?: string }[];
    };
  };
};

/**
 * YouTube's player API, asked as the Android app: the watch page answers Cloudflare's
 * addresses with a captcha, this endpoint mostly does not. Not a public API, so it can
 * change under us; the caller falls back to the model watching the video.
 */
async function youtubePlayer(id: string): Promise<YoutubePlayer> {
  const res = await fetch("https://www.youtube.com/youtubei/v1/player?prettyPrint=false", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      context: { client: { clientName: "ANDROID", clientVersion: "20.10.38" } },
      videoId: id,
    }),
  });
  if (!res.ok) return {};
  return (await res.json()) as YoutubePlayer;
}

/** Caption XML to plain text: the words of every cue, entities decoded. */
export function captionText(xml: string): string {
  return [...xml.matchAll(/<(text|p)\b[^>]*>([\s\S]*?)<\/\1>/g)]
    .map((m) => m[2].replace(/<[^>]+>/g, ""))
    .join(" ")
    .replace(/&amp;/g, "&")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * The video's details and caption text. Either may be missing: YouTube sometimes
 * bot-checks a Worker's address (one retry), and some videos have no captions.
 */
async function youtubeTranscript(
  id: string
): Promise<{ details: YoutubeDetails | null; transcript: string }> {
  let player = await youtubePlayer(id);
  if (player.playabilityStatus?.status !== "OK") player = await youtubePlayer(id);
  if (player.playabilityStatus?.status !== "OK") return { details: null, transcript: "" };
  const v = player.videoDetails ?? {};
  const details = {
    title: v.title ?? "",
    channel: v.author ?? "",
    seconds: Number(v.lengthSeconds) || 0,
  };
  const tracks = player.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  const english = tracks.filter((t) => t.languageCode.startsWith("en"));
  // Uploaded captions over automatic ones; English over the rest.
  const track =
    english.find((t) => t.kind !== "asr") ??
    english[0] ??
    tracks.find((t) => t.kind !== "asr") ??
    tracks[0];
  if (!track) return { details, transcript: "" };
  const res = await fetch(track.baseUrl.replace("&fmt=srv3", ""));
  if (!res.ok) return { details, transcript: "" };
  return { details, transcript: captionText(await res.text()) };
}

